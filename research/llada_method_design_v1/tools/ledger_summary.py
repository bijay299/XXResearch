#!/usr/bin/env python3
"""Summarise ledger/resources.jsonl (+ manual.jsonl) into ledger/SUMMARY.md."""
import collections
import json
import os

D = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ledger")
recs = [json.loads(l) for l in open(os.path.join(D, "resources.jsonl")) if l.strip()]
man = [json.loads(l) for l in open(os.path.join(D, "manual.jsonl")) if l.strip()]
agg = collections.defaultdict(lambda: {"runs": 0, "wall_s": 0.0, "cpu_s": 0.0, "max_rss_mib": 0.0, "failed": 0})
for r in recs:
    a = agg[r["agent"]]
    a["runs"] += 1
    a["wall_s"] += r["wall_s"]
    a["cpu_s"] += r["cpu_s"]
    a["max_rss_mib"] = max(a["max_rss_mib"], r["max_rss_mib"])
    a["failed"] += r["rc"] != 0
tot_cpu = sum(a["cpu_s"] for a in agg.values())
lines = ["# Resource ledger summary (generated by tools/ledger_summary.py)", "",
         "Observed = child processes run through `tools/ledger_run.py` (user+sys CPU seconds, wall, max RSS per process).",
         "Not captured: agent reasoning, file edits, git, the processes listed in manual.jsonl.", "",
         "| agent | wrapped runs | failed (rc≠0) | wall s (sum) | CPU s (sum) | CPU core-h | max RSS MiB (one process) |",
         "|---|---|---|---|---|---|---|"]
for k in sorted(agg):
    a = agg[k]
    lines.append(f"| {k} | {a['runs']} | {a['failed']} | {a['wall_s']:.0f} | {a['cpu_s']:.0f} | {a['cpu_s']/3600:.2f} | {a['max_rss_mib']:.0f} |")
lines += ["", f"**Total observed CPU: {tot_cpu/3600:.2f} core-hours** (ceiling 48; machine maximum over 8 h = 32).", "",
          "Manual (unwrapped) records:", ""]
for m in man:
    lines.append(f"- {m['ts_utc']} [{m['agent']}] {m['label']} — wall {m.get('wall_s')} s, CPU {m.get('cpu_s')}, basis: {m['basis']}")
open(os.path.join(D, "SUMMARY.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
