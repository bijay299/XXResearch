#!/usr/bin/env python3
"""Bind the FIXED reference evaluations by content. CPU only.

The two reference arms -- the parent MA and the L2 endpoint -- define the
suppression target every candidate dump is matched to. If they are regenerated
alongside each new candidate scan, that target can move: a reference evaluation
measuring 45 pp instead of 30 pp changes the number everything is compared
against, and a bridge that only looks at the candidate would not notice.

So the references are read from one fixed location, read-only, and this records
exactly which bytes were relied on: the detections digest and row count, the
image-report digest, the digest of the checkpoint that generated the images, the
manifest identity, and the generation-settings source.

    python scripts/seq/bind_reference_evals.py \
        --reference_dev_root <diag_v1>/eval_dev --seeds "17 29" \
        --expect_manifest_sha <sha> --out <new_root>/reference_bindings.json
"""
from __future__ import annotations

import argparse
import datetime
import hashlib
import json
import sys
from pathlib import Path


def sha256_file(p: Path, chunk: int = 1 << 20) -> str:
    h = hashlib.sha256()
    with p.open("rb") as fh:
        for b in iter(lambda: fh.read(chunk), b""):
            h.update(b)
    return h.hexdigest()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--reference_dev_root", required=True)
    ap.add_argument("--seeds", default="17 29")
    ap.add_argument("--expect_manifest_sha", default=None)
    ap.add_argument("--registry", default="configs/legacy_training_artifacts.json")
    ap.add_argument("--slots", default="MA MAB_L2")
    ap.add_argument("--expect_slots_index", default=None,
                    help="a published per-slot index (e.g. the evidence "
                         "bundle's development_slots_index.json). Each "
                         "reference evaluation's detections and image-report "
                         "digests must match it, so a reference whose "
                         "measurements were edited cannot be reused as if it "
                         "were the verified original.")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    ref = Path(a.reference_dev_root)
    seeds = a.seeds.replace(",", " ").split()
    slots = a.slots.replace(",", " ").split()
    registered = {}
    rp = Path(a.registry)
    if rp.is_file():
        for art in json.loads(rp.read_text()).get("artifacts", []):
            registered[art.get("id")] = art.get("delta_sha256")

    published: dict = {}
    if a.expect_slots_index:
        ip = Path(a.expect_slots_index)
        if not ip.is_file():
            print(f"PROBLEM: published slot index {ip} not found")
            return 1
        for row in json.loads(ip.read_text()).get("slots", []):
            published[row.get("slot")] = row

    rec: dict = {}
    bad: list[str] = []
    for s in seeds:
        for slot in slots:
            name = f"seed{s}_{slot}"
            d = ref / name
            det, irp = d / "detections.jsonl", d / "image_report.json"
            if not (det.is_file() and irp.is_file()):
                bad.append(f"{name}: incomplete reference evaluation at {d}")
                continue
            ir = json.loads(irp.read_text())
            rows = sum(1 for line in det.read_text().splitlines() if line.strip())
            gen_ck = (ir.get("checkpoint_load") or {}).get("sha256")
            want_ck = registered.get(f"seed{s}/{slot}")
            entry = {
                "detections_path": str(det),
                "detections_sha256": sha256_file(det),
                "detection_rows": rows,
                "image_report_sha256": sha256_file(irp),
                "generating_checkpoint_sha256": gen_ck,
                "generating_checkpoint_path": (ir.get("checkpoint_load")
                                               or {}).get("unet_ckpt"),
                "registered_checkpoint_sha256": want_ck,
                "generated_by_the_registered_saved_artifact":
                    bool(want_ck) and gen_ck == want_ck,
                "manifest_sha256": ir.get("manifest_sha256"),
                "generation_settings_source": ir.get("generation_settings_source"),
                "images_complete": ir.get("complete"),
                "n_images": ir.get("generated_or_reused"),
            }
            if registered and not entry["generated_by_the_registered_saved_artifact"]:
                bad.append(f"{name}: generated by {str(gen_ck)[:12]}…, not the "
                           f"registered saved artifact {str(want_ck)[:12]}…")
            if a.expect_manifest_sha and entry["manifest_sha256"] != a.expect_manifest_sha:
                bad.append(f"{name}: manifest {str(entry['manifest_sha256'])[:12]}… "
                           f"!= frozen {a.expect_manifest_sha[:12]}…")
            if entry["images_complete"] is not True:
                bad.append(f"{name}: image_report.complete is "
                           f"{entry['images_complete']!r}")
            if published:
                pub = published.get(name)
                if pub is None:
                    bad.append(f"{name}: not in the published slot index, so it "
                               f"is not one of the verified original "
                               f"evaluations")
                else:
                    entry["published_detections_sha256"] = \
                        (pub.get("detections.jsonl") or {}).get("sha256")
                    entry["published_image_report_sha256"] = \
                        (pub.get("image_report.json") or {}).get("sha256")
                    entry["matches_published_index"] = (
                        entry["detections_sha256"]
                        == entry["published_detections_sha256"]
                        and entry["image_report_sha256"]
                        == entry["published_image_report_sha256"])
                    if not entry["matches_published_index"]:
                        bad.append(
                            f"{name}: its measurements differ from the "
                            f"published, verified original "
                            f"(detections {entry['detections_sha256'][:12]}… vs "
                            f"{str(entry['published_detections_sha256'])[:12]}…). "
                            f"A reference evaluation that has been rewritten is "
                            f"not the fixed reference.")
            rec[name] = entry

    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps({
        "_what_this_is": (
            "Content bindings for the FIXED reference evaluations this run "
            "matches to. They are read-only here and are NOT regenerated in "
            "this output root, so the suppression target cannot move while "
            "candidates are scored."),
        "generated_utc": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "reference_dev_root": str(ref),
        "frozen_dev_manifest_sha256": a.expect_manifest_sha,
        "registry": str(rp) if rp.is_file() else None,
        "slots": rec,
        "problems": bad,
        "ok": not bad and len(rec) == len(seeds) * len(slots),
    }, indent=2) + "\n")

    for m in bad:
        print(f"PROBLEM: {m}")
    print(f"bound {len(rec)} fixed reference evaluation(s) -> {out}")
    return 1 if (bad or len(rec) != len(seeds) * len(slots)) else 0


if __name__ == "__main__":
    raise SystemExit(main())
