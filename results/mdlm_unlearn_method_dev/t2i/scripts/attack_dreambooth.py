"""DreamBooth relearning attack — IMMA's third target method.

DreamBooth differs from the plain full-UNet fine-tuning this phase has used in two ways, and both
are implemented here:

  1. IDENTIFIER BINDING. The concept is bound to a rare token ("sks") paired with a class noun,
     e.g. "a photo of a sks church", rather than trained on the concept word directly.
  2. PRIOR-PRESERVATION LOSS. A second loss term on CLASS images generated by the model itself
     ("a photo of a church"), weighted by --prior-weight, which is what keeps DreamBooth from
     collapsing the class while it learns the identifier.

Without (2) this would just be the full fine-tuning attack with a different prompt, so the prior
term is the point. Evaluated on identifier prompts, like Textual Inversion -- so this H is likewise
NOT interchangeable with a weight-space attack's H on concept-word prompts.
"""
import argparse, json, os, time
import torch
import torch.nn.functional as F

OUT = "/data/bijaypandey/t2i_unlearn/outputs"


def _ar():
    import importlib.util as iu
    spec = iu.spec_from_file_location(
        "ar_db", os.path.join(os.path.dirname(os.path.abspath(__file__)), "attack_relearn.py"))
    m = iu.module_from_spec(spec); spec.loader.exec_module(m)
    return m


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--unet", default=None)
    ap.add_argument("--text-encoder", default=None)
    ap.add_argument("--concept", required=True)
    ap.add_argument("--steps", type=int, default=300)
    ap.add_argument("--lr", type=float, default=1e-5)
    ap.add_argument("--n-images", type=int, default=16)
    ap.add_argument("--n-class-images", type=int, default=16)
    ap.add_argument("--prior-weight", type=float, default=1.0)
    ap.add_argument("--identifier", default="sks")
    ap.add_argument("--gate", type=float, default=0.20)
    ap.add_argument("--eval-n", type=int, default=5)
    ap.add_argument("--eval-steps", type=int, default=25)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--label", required=True)
    a = ap.parse_args()
    dev = "cuda"
    torch.manual_seed(a.seed)
    ar = _ar()
    cls = {"van_gogh": "van gogh painting", "garbage_truck": "garbage truck"}.get(
        a.concept, a.concept.replace("_", " "))
    T_real, H_real = ar.SPLIT[a.concept]["T"], ar.SPLIT[a.concept]["H"]

    def ident(ps):
        out = []
        for p in ps:
            q = p.lower()
            for w in (cls, a.concept.split("_")[0]):
                if w and w in q:
                    q = q.replace(w, f"{a.identifier} {cls}"); break
            else:
                q = f"{q} {a.identifier} {cls}"
            out.append(q)
        return out
    T, H = ident(T_real), ident(H_real)

    from transformers import CLIPModel, CLIPProcessor
    cm = CLIPModel.from_pretrained("openai/clip-vit-large-patch14",
                                   torch_dtype=torch.float16).to(dev).eval()
    cp = CLIPProcessor.from_pretrained("openai/clip-vit-large-patch14")
    with torch.no_grad():
        ti = cp(text=[f"a photo of a {l}" for l in ar.LABELS], return_tensors="pt",
                padding=True).to(dev)
        tfeat = cm.get_text_features(**ti); tfeat = tfeat / tfeat.norm(dim=-1, keepdim=True)

    base = ar.build_pipe(torch.float16, None, dev)
    inst_imgs, inst_caps, cls_imgs, cls_caps = [], [], [], []
    for i in range(a.n_images):
        g = torch.Generator(device=dev).manual_seed(10_000 + i)
        inst_imgs.append(base([T_real[i % len(T_real)]], num_inference_steps=25,
                              guidance_scale=7.5, generator=g).images[0])
        inst_caps.append(T[i % len(T)])
    # PRIOR-PRESERVATION set: the attacked model's OWN class images, per DreamBooth
    pri = ar.build_pipe(torch.float16, a.unet, dev, te_path=a.text_encoder)
    for i in range(a.n_class_images):
        g = torch.Generator(device=dev).manual_seed(20_000 + i)
        cls_imgs.append(pri([f"a photo of a {cls}"], num_inference_steps=25, guidance_scale=7.5,
                            generator=g).images[0])
        cls_caps.append(f"a photo of a {cls}")
    del base, pri; torch.cuda.empty_cache()

    pipe = ar.build_pipe(torch.float32, a.unet, dev, te_path=a.text_encoder)
    unet, vae, te, tok, sch = pipe.unet, pipe.vae, pipe.text_encoder, pipe.tokenizer, pipe.scheduler
    te.requires_grad_(False); vae.requires_grad_(False); unet.requires_grad_(True)

    with torch.no_grad():
        half = ar.build_pipe(torch.float16, a.unet, dev, te_path=a.text_encoder)
        T_before = ar.clip_acc(half, cm, cp, tfeat, T, a.concept, 3, a.eval_steps, a.seed, dev)
        H_before = ar.clip_acc(half, cm, cp, tfeat, H, a.concept, a.eval_n, a.eval_steps, a.seed, dev)
        del half; torch.cuda.empty_cache()
    print(f"[db] BEFORE (identifier prompts) T={T_before:.3f} H={H_before:.3f}", flush=True)

    def encode(ims, caps):
        with torch.no_grad():
            lat = []
            for im in ims:
                x = torch.from_numpy((torch.frombuffer(im.tobytes(), dtype=torch.uint8)
                     .reshape(im.size[1], im.size[0], 3).numpy())).permute(2, 0, 1)[None].float().to(dev) / 127.5 - 1.0
                lat.append(vae.encode(x).latent_dist.sample() * vae.config.scaling_factor)
            ids = torch.cat([tok([c], padding="max_length", max_length=77, truncation=True,
                                 return_tensors="pt").input_ids for c in caps]).to(dev)
            return torch.cat(lat), torch.cat([te(ids[k:k+1])[0] for k in range(len(caps))])
    i_lat, i_emb = encode(inst_imgs, inst_caps)
    c_lat, c_emb = encode(cls_imgs, cls_caps)

    opt = torch.optim.Adam(unet.parameters(), lr=a.lr)
    unet.train(); t0 = time.time()
    for step in range(a.steps):
        def term(lat, emb):
            i = torch.randint(0, len(lat), (1,), device=dev)
            n = torch.randn_like(lat[i])
            ts = torch.randint(0, sch.config.num_train_timesteps, (1,), device=dev).long()
            return F.mse_loss(unet(sch.add_noise(lat[i], n, ts), ts,
                                   encoder_hidden_states=emb[i]).sample, n)
        li = term(i_lat, i_emb)
        lp = term(c_lat, c_emb)
        loss = li + a.prior_weight * lp
        opt.zero_grad(set_to_none=True); loss.backward()
        torch.nn.utils.clip_grad_norm_(unet.parameters(), 1.0); opt.step()
        if step % 50 == 0 or step == a.steps - 1:
            print(f"[db] step {step:4d} inst={li.item():.5f} prior={lp.item():.5f} "
                  f"{(time.time()-t0)/max(step+1,1):.2f}s/step", flush=True)

    unet.eval()
    tmp = f"/data/bijaypandey/t2i_unlearn/adapters/_db_{a.label}"
    os.makedirs(tmp, exist_ok=True)
    torch.save({k: v.half() for k, v in unet.state_dict().items()}, f"{tmp}/unet.pt")
    del unet, opt, pipe; torch.cuda.empty_cache()
    after = ar.build_pipe(torch.float16, f"{tmp}/unet.pt", dev, te_path=a.text_encoder)
    with torch.no_grad():
        T_after = ar.clip_acc(after, cm, cp, tfeat, T, a.concept, 3, a.eval_steps, a.seed, dev)
        H_after = ar.clip_acc(after, cm, cp, tfeat, H, a.concept, a.eval_n, a.eval_steps, a.seed, dev)
    os.system(f"rm -rf {tmp}")

    valid = (T_after - T_before) >= a.gate
    json.dump({"study": "t2i_dreambooth_attack", "label": a.label, "concept": a.concept,
               "hparams": vars(a), "class_noun": cls,
               "adversary": {"kind": "DreamBooth (identifier binding + prior preservation)",
                             "identifier": a.identifier, "prior_weight": a.prior_weight,
                             "n_instance": a.n_images, "n_class": a.n_class_images,
                             "note": "full-UNet trainable, as in DreamBooth. The prior term uses "
                                     "class images generated by the ERASED model itself."},
               "evaluation_surface": "identifier prompts, so H is NOT interchangeable with a "
                                     "concept-word H",
               "T_prompts": T, "H_prompts": H,
               "attack_validity": {"T_before": T_before, "T_after": T_after,
                                   "T_rise": T_after - T_before, "gate": a.gate,
                                   "valid": bool(valid)},
               "recovery": {"H_before": H_before, "H_after": H_after}},
              open(f"{OUT}/atk_{a.label}.json", "w"), indent=1)
    print(f"[db] {a.label}: T {T_before:.3f}->{T_after:.3f} (gate "
          f"{'PASS' if valid else 'FAIL'}) | H {H_before:.3f}->{H_after:.3f}", flush=True)


if __name__ == "__main__":
    main()
