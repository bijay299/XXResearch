#!/bin/bash
# Runs a list of arm jobs across the GPUs allocated to this sprint, two at a time.
# Each line of the job file is:  <gpu-agnostic job name>|<run_arm.py arguments>
# Usage: drive.sh <jobfile> <gpu_a> <gpu_b>
set -u
SPRINT=/data/bijaypandey/cuig_pilot/block_object_sprint
source $SPRINT/env/runenv.sh
JOBFILE=$1; GA=${2:-0}; GB=${3:-3}
mkdir -p $SPRINT/logs/arms

run_one () {   # $1 = gpu, $2 = name, $3 = args
  local gpu=$1 name=$2 args=$3
  local S=$(date +%s)
  CUDA_VISIBLE_DEVICES=$gpu PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True \
    $VENV/bin/python $SPRINT/code/run_arm.py $args \
    > $SPRINT/logs/arms/$name.log 2>&1
  local ec=$? W=$(( $(date +%s)-S ))
  local n=$(grep -oE 'wrote [0-9]+ images' $SPRINT/logs/arms/$name.log | grep -oE '[0-9]+' | head -1)
  n=${n:-0}
  echo "$name|gpu$gpu|exit=$ec|wall=${W}s|images=$n" >> $SPRINT/logs/arms/_results.txt
  python3 $SPRINT/code/ledger.py job "$name" "${PHASE:-integration_baseline}" 1 "$W" "$n" "arm job on gpu $gpu" >/dev/null
  if [ "$n" != "0" ]; then
    python3 $SPRINT/code/ledger.py images "$name" "$n" "generated by run_arm.py" >/dev/null
  fi
  echo "[done] $name gpu$gpu exit=$ec wall=${W}s images=$n"
}

mapfile -t JOBS < <(grep -vE '^\s*#|^\s*$' "$JOBFILE")
i=0
while [ $i -lt ${#JOBS[@]} ]; do
  nameA=${JOBS[$i]%%|*}; argsA=${JOBS[$i]#*|}
  run_one $GA "$nameA" "$argsA" &
  PA=$!
  PB=""
  if [ $((i+1)) -lt ${#JOBS[@]} ]; then
    nameB=${JOBS[$((i+1))]%%|*}; argsB=${JOBS[$((i+1))]#*|}
    run_one $GB "$nameB" "$argsB" &
    PB=$!
  fi
  wait $PA; [ -n "$PB" ] && wait $PB
  i=$((i+2))
done
echo "=== all jobs done ==="
cat $SPRINT/logs/arms/_results.txt
